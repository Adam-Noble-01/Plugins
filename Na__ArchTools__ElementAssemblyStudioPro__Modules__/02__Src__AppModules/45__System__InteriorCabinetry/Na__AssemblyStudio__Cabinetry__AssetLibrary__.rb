require 'json'
require_relative '../03__AppUtils/Na__AssemblyStudio__AppUtils__DebugTools__'
require_relative '../02__AppData/Na__AssemblyStudio__AppData__ConfigLoader__'

module Na__AssemblyStudio
module Na__InteriorCabinetrySystem
    module Na__AssetLibrary

# -----------------------------------------------------------------------------
# REGION | Module References and Constants
# -----------------------------------------------------------------------------

        DebugTools   = Na__AssemblyStudio::Na__AppUtils::Na__DebugTools
        ConfigLoader = Na__AssemblyStudio::Na__AppData::Na__ConfigLoader

        NA_ASSETS_ROOT_FALLBACK = File.expand_path(File.join(File.dirname(__FILE__), "..", "..", "04__Data__AssetLibrary")).freeze
        NA_BUCKET_FALLBACKS = {
            :legs    => "Cabinetry__Legs__",
            :handles => "Cabinetry__Handles__"
        }.freeze

# endregion -------------------------------------------------------------------

# -----------------------------------------------------------------------------
# REGION | Module Variables
# -----------------------------------------------------------------------------

        @na_cache = {}                                                         # <-- "bucket|key" -> parsed asset Hash

# endregion -------------------------------------------------------------------

# -----------------------------------------------------------------------------
# REGION | Public API
# -----------------------------------------------------------------------------

        # FUNCTION | Load One Asset by Bucket and Key (Cached)
        # ------------------------------------------------------------
        # @param bucket [Symbol] :legs | :handles
        # @param key    [String] file stem without the trailing "__.json"
        # @return [Hash, nil]
        def self.na_load(bucket, key)
            cache_key = "#{bucket}|#{key}"
            return @na_cache[cache_key] if @na_cache.key?(cache_key)

            folder = na_bucket_path(bucket)
            path   = folder && File.join(folder, "#{key}__.json")
            unless path && File.exist?(path)
                DebugTools.na_debug_warn("Cabinetry asset not found: #{bucket} '#{key}'")
                return nil
            end

            data = JSON.parse(File.read(path, encoding: "UTF-8"))
            @na_cache[cache_key] = data
            DebugTools.na_debug_asset("Loaded cabinetry asset '#{key}' (#{bucket})")
            data
        rescue JSON::ParserError, SystemCallError => e
            DebugTools.na_debug_error("Cabinetry asset unreadable: #{bucket} '#{key}'", e)
            nil
        end
        # ---------------------------------------------------------------

        # FUNCTION | Every Asset Key in a Bucket, Sorted
        # ------------------------------------------------------------
        def self.na_list(bucket)
            folder = na_bucket_path(bucket)
            return [] unless folder && Dir.exist?(folder)
            Dir.glob(File.join(folder, "*.json")).map { |path| File.basename(path, ".json").sub(/__\z/, "") }
               .reject { |key| key.start_with?("_") }
               .sort
        end
        # ---------------------------------------------------------------

        # FUNCTION | The Display Name of an Asset (Na__Asset__Name), or Its Key
        # ------------------------------------------------------------
        def self.na_display_name(bucket, key)
            asset    = na_load(bucket, key)
            metadata = asset.is_a?(Hash) ? asset["Na__Asset__Metadata"] : nil
            name     = metadata.is_a?(Hash) ? metadata["Na__Asset__Name"].to_s.strip : ""
            name.empty? ? key.to_s : name
        end
        # ---------------------------------------------------------------

        # FUNCTION | One Field of an Asset's Na__Asset__Metadata Block
        # ------------------------------------------------------------
        def self.na_metadata_value(asset, field, fallback = nil)
            metadata = asset.is_a?(Hash) ? asset["Na__Asset__Metadata"] : nil
            return fallback unless metadata.is_a?(Hash) && metadata.key?(field)
            metadata[field]
        end
        # ---------------------------------------------------------------

        # FUNCTION | Forget Every Parsed Asset (Developer Reload, Options Refresh)
        # ------------------------------------------------------------
        def self.na_clear_cache
            @na_cache = {}
        end
        # ---------------------------------------------------------------

# endregion -------------------------------------------------------------------

# -----------------------------------------------------------------------------
# REGION | Internal Helpers
# -----------------------------------------------------------------------------

        # HELPER FUNCTION | Absolute Folder of a Bucket (AppConfig, Then Fallback)
        # ------------------------------------------------------------
        def self.na_bucket_path(bucket)
            fallback = NA_BUCKET_FALLBACKS[bucket]
            return nil unless fallback

            root_name = nil
            name      = nil
            begin
                root_name = ConfigLoader.na_get("assetLibrary", "rootFolder")
                section   = ConfigLoader.na_get("assetLibrary", "cabinetry")
                name      = section[bucket.to_s] if section.is_a?(Hash)
            rescue StandardError => e
                DebugTools.na_debug_warn("Cabinetry asset AppConfig lookup failed: #{e.message}")
            end

            root = root_name.to_s.strip.empty? ? NA_ASSETS_ROOT_FALLBACK :
                   File.expand_path(File.join(File.dirname(__FILE__), "..", "..", root_name.to_s))
            File.join(root, name.to_s.strip.empty? ? fallback : name.to_s)
        end
        private_class_method :na_bucket_path
        # ---------------------------------------------------------------

# endregion -------------------------------------------------------------------

    end # module Na__AssetLibrary
end # module Na__InteriorCabinetrySystem
end # module Na__AssemblyStudio

